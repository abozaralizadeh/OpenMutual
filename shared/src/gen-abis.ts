// Copies contract ABIs from the Foundry build into a typed file the apps can import.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { CONTRACT_NAMES, projectRoot } from './paths';

const root = projectRoot();
const parts = CONTRACT_NAMES.map((name) => {
  const artifact = JSON.parse(readFileSync(join(root, 'contracts/out', `${name}.sol`, `${name}.json`), 'utf8'));
  return `export const ${name}Abi = ${JSON.stringify(artifact.abi)} as const;`;
});
writeFileSync(join(root, 'shared/src/generated/abis.ts'), `// Generated by npm run gen -w shared. Don't edit by hand.\n${parts.join('\n')}\n`);
console.log(`Wrote ${CONTRACT_NAMES.length} ABIs`);
